/**
 * Seraph Wings cosmetic: a plain vanilla model layer on the player body. The rig (root > mid > tip > primary fan per
 * wing) and its keyframed clips are generated by {@code tools/dev/gen_seraph_wings.py} into {@link SeraphWingsRig} and
 * played by {@link Keyframes}. Kept vanilla instead of GeckoLib so it works with every player renderer, shader pack
 * and skin layer mod. Folded and breathing at rest, blends into the spread glide while falling, and plays the burst
 * clip when the Seraph set's Glide Burst fires (synced via {@code AVAttachments.WING_BURST}).
 */
