    static final ContextKey<Boolean> SHOWN = new ContextKey<>(AstralVigil.id("wings_shown"));
    static final ContextKey<Float> GLIDE = new ContextKey<>(AstralVigil.id("wings_glide"));
    static final ContextKey<Float> BURST = new ContextKey<>(AstralVigil.id("wings_burst"));
