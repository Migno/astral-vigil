    public static boolean shown(Player player) {
        return player.getData(AVAttachments.WINGS) == SeraphFeatherItem.SHOWN || cosmetic(player) != null;
    }

    /** Developer wing cosmetic (radiant/eclipse recolour with an emissive pass), or null for the plain Seraph Wings. */
    static media.hofferbert.astralvigil.cosmetics.Cosmetic cosmetic(Player player) {
        return player.getData(AVAttachments.COSMETICS).get(media.hofferbert.astralvigil.cosmetics.Cosmetic.Slot.WINGS).orElse(null);
    }

    static Identifier texture(media.hofferbert.astralvigil.cosmetics.Cosmetic cosmetic) {
        return cosmetic == null ? TEXTURE : media.hofferbert.astralvigil.client.cosmetics.CosmeticLayer.texture(cosmetic);
    }

    static boolean gliding(Player player) {
        return !player.onGround() && player.getDeltaMovement().y < -0.08 && !player.getAbilities().flying;
    }

    private static final Map<Object, float[]> BLEND = new WeakHashMap<>();
    private static final float BURST_FADE_IN = 0.05f;
    private static final float BURST_FADE_OUT = 0.15f;

    /** Smoothed 0..1 fold-to-glide blend per player (eases in over ~half a second, out a little faster). */
    static float glideBlend(Object entity, float ageInTicks, boolean gliding) {
        float[] s = BLEND.computeIfAbsent(entity, k -> new float[] {ageInTicks, 0f});
        float dt = Mth.clamp(ageInTicks - s[0], 0f, 10f);
        s[0] = ageInTicks;
        float rate = gliding ? 0.18f : 0.25f;
        s[1] += ((gliding ? 1f : 0f) - s[1]) * (1f - (float) Math.exp(-rate * dt));
        return s[1];
    }

    /** Seconds since the player's last Glide Burst, or -1 when no burst clip is playing. */
    static float burstTime(Player player, float ageInTicks) {
        long at = player.getData(AVAttachments.WING_BURST);
        if (at <= 0L) {
            return -1f;
        }
        float t = (player.level().getGameTime() - at + (ageInTicks - Mth.floor(ageInTicks))) / 20f;
        return t >= 0f && t <= SeraphWingsRig.BURST.length() ? t : -1f;
    }

    static void addWings(PartDefinition body) {
        SeraphWingsRig.addWings(body);
    }

    static ModelPart[] parts(ModelPart body) {
        ModelPart[] parts = new ModelPart[SeraphWingsRig.BONES.length];
        for (int i = 0; i < parts.length; i++) {
            int parent = SeraphWingsRig.PARENT[i];
            parts[i] = (parent < 0 ? body : parts[parent]).getChild(SeraphWingsRig.BONES[i]);
        }
        return parts;
    }

    /**
     * Idle (folded, breathing; developer wings rest half-open with a slow beat instead) blended into the glide by
     * {@code glide}, with the burst clip layered on top.
     */
    static void pose(ModelPart[] parts, float ageInTicks, float glide, float burst, boolean display) {
        float t = ageInTicks / 20f;
        float weight = burst < 0f ? 0f
                : Math.min(Math.min(1f, burst / BURST_FADE_IN), (SeraphWingsRig.BURST.length() - burst) / BURST_FADE_OUT);
        float[] a = new float[3];
        float[] b = new float[3];
        for (int i = 0; i < parts.length; i++) {
            (display ? SeraphWingsRig.DISPLAY : SeraphWingsRig.IDLE).sample(i, t, a);
            if (glide > 0f) {
                SeraphWingsRig.GLIDE.sample(i, t, b);
                lerp(a, b, glide);
            }
            if (weight > 0f) {
                SeraphWingsRig.BURST.sample(i, burst, b);
                lerp(a, b, Mth.clamp(weight, 0f, 1f));
            }
            float[] rest = SeraphWingsRig.REST[i];
            parts[i].setRotation(rest[0] + a[0] * Mth.DEG_TO_RAD, rest[1] + a[1] * Mth.DEG_TO_RAD, rest[2] + a[2] * Mth.DEG_TO_RAD);
        }
    }

    private static void lerp(float[] a, float[] b, float k) {
        for (int c = 0; c < 3; c++) {
            a[c] += (b[c] - a[c]) * k;
        }
    }

